#!/usr/bin/env python3
"""Restore an existing local candidate in a hash-isolated cache; never pack or publish."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import xml.etree.ElementTree as ET
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
MARKER = '<!-- Generated by build/use-codingrules-candidate.py -->'


def verify_restore(package, project):
    assets = json.loads((project.parent / 'obj/project.assets.json').read_text())
    with ZipFile(package) as archive:
        metadata = ET.fromstring(archive.read('Anton.CodingRules.nuspec'))
        version = metadata.find('{*}metadata/{*}version').text
        library = assets['libraries'][f'Anton.CodingRules/{version}']
        restored = [Path(folder) / library['path'] for folder in assets['packageFolders']
                    if (Path(folder) / library['path']).is_dir()]
        if len(restored) != 1:
            raise ValueError('Expected exactly one restored CodingRules directory.')
        restored = restored[0]
        if (restored / f'anton.codingrules.{version}.nupkg').read_bytes() != package.read_bytes():
            raise ValueError('Restored archive differs from the supplied candidate.')
        names = [name for name in archive.namelist()
                 if name.startswith(('analyzers/', 'buildTransitive/', 'config/', 'agent-guidance/'))
                 and not name.endswith('/')]
        for name in names:
            if (restored / name).read_bytes() != archive.read(name):
                raise ValueError(f'Restored asset differs: {name}')
        print(f'Verified {len(names)} analyzer/fix/configuration/guidance assets in {restored}')
        return restored


def verify_graph(package, project):
    pending, visited = [project], set()
    while pending:
        current = pending.pop()
        if current in visited:
            continue
        visited.add(current)
        verify_restore(package, current)
        assets = json.loads((current.parent / 'obj/project.assets.json').read_text())
        for framework in assets['project']['restore']['frameworks'].values():
            pending.extend(Path(path).resolve() for path in framework.get('projectReferences', {}))
    print(f'Verified candidate throughout {len(visited)} projects in the restored graph.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('package', type=Path, help='An already-packed Anton.CodingRules nupkg.')
    parser.add_argument('--project', default='src/MainCli/Tests/MainCli.Tests.csproj')
    args = parser.parse_args()
    package = args.package.resolve()
    project = (ROOT / args.project).resolve()
    if not project.is_relative_to(ROOT):
        parser.error('The project must be in this repository.')
    config = ROOT / 'NuGet.Config'
    if config.exists() and MARKER not in config.read_text():
        parser.error('Refusing to replace an existing hand-written NuGet.Config.')
    digest = hashlib.sha256(package.read_bytes()).hexdigest()
    with ZipFile(package) as archive:
        metadata = ET.fromstring(archive.read('Anton.CodingRules.nuspec'))
        if metadata.find('{*}metadata/{*}id').text != 'Anton.CodingRules':
            parser.error('Expected an Anton.CodingRules archive.')
        version = metadata.find('{*}metadata/{*}version').text
        source_commit = metadata.find('{*}metadata/{*}repository').get('commit')
    # Preserve enabled machine feeds for the application's other dependencies.
    # Exact-ID mapping prevents the same package version coming from any of them.
    sources = subprocess.check_output(['dotnet', 'nuget', 'list', 'source', '--format', 'Short'],
                                      cwd=ROOT, text=True).splitlines()
    sources = [line[2:] for line in sources if line.startswith('E ')]
    if config.exists():
        old = ET.parse(config).find('packageSources')
        sources = [item.get('value') for item in old.findall('add') if item.get('key') != 'candidate']
    local = ROOT / 'tmp' / ('codingrules-' + digest)
    feed = local / 'feed'
    feed.mkdir(parents=True, exist_ok=True)
    candidate = feed / f'Anton.CodingRules.{version}.nupkg'
    shutil.copyfile(package, candidate)
    settings = ET.Element('configuration')
    options = ET.SubElement(settings, 'config')
    ET.SubElement(options, 'add', key='globalPackagesFolder', value=str(local / 'packages'))
    feeds = ET.SubElement(settings, 'packageSources')
    ET.SubElement(feeds, 'clear')
    ET.SubElement(feeds, 'add', key='candidate', value=str(feed))
    mapping = ET.SubElement(settings, 'packageSourceMapping')
    ET.SubElement(mapping, 'clear')
    selected = ET.SubElement(mapping, 'packageSource', key='candidate')
    ET.SubElement(selected, 'package', pattern='Anton.CodingRules')
    for index, source in enumerate(sources):
        key = f'application-feed-{index}'
        ET.SubElement(feeds, 'add', key=key, value=source)
        selected = ET.SubElement(mapping, 'packageSource', key=key)
        ET.SubElement(selected, 'package', pattern='*')
    config.write_text(MARKER + '\n' + ET.tostring(settings, encoding='unicode') + '\n')
    subprocess.run(['dotnet', 'restore', str(project), '--force', '--no-http-cache'], cwd=ROOT, check=True)
    restored = verify_restore(candidate, project)
    verify_graph(candidate, project)
    subprocess.run(['dotnet', 'msbuild', str(project), '-t:ExportCodingRulesAgentGuidance',
                    '-p:CodingRulesAgentGuidanceDirectory=' + str(ROOT / '.codingrules')], cwd=ROOT, check=True)
    if (ROOT / '.codingrules/agent-coding-rules.md').read_bytes() != (restored / 'agent-guidance/agent-coding-rules.md').read_bytes():
        raise ValueError('Exported guidance differs from the candidate.')
    record = dict(package=package.name, version=version, source_commit=source_commit, sha256=digest)
    (local / 'candidate.json').write_text(json.dumps(record, indent=2) + '\n')
    print(json.dumps(record, indent=2))


if __name__ == '__main__':
    main()
